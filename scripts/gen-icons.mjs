// Generates Icons.kt from the Lucide icon set (lucide-static, ISC license).
// Usage: node gen-icons.mjs <lucide-static/icons dir> <output Icons.kt>
import fs from "fs";
import path from "path";

const [dir, out] = process.argv.slice(2);

// Kotlin name -> candidate Lucide names (first one that exists is used)
const ICONS = {
  Timer: ["timer"],
  Log: ["list"],
  Stats: ["chart-column", "bar-chart-3"],
  Folder: ["folder"],
  Settings: ["settings"],
  Plus: ["plus"],
  Trash: ["trash-2"],
  Pencil: ["pencil"],
  Play: ["play"],
  Pause: ["pause"],
  Download: ["download"],
  Upload: ["upload"],
  ChevronDown: ["chevron-down"],
};

const attrs = (s) => Object.fromEntries([...s.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const n = (v) => Number(v);

function rect(a) {
  const x = n(a.x || 0), y = n(a.y || 0), w = n(a.width), h = n(a.height);
  const r = Math.min(n(a.rx || a.ry || 0), w / 2, h / 2);
  if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
  return (
    `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}` +
    `a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}` +
    `v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`
  );
}

function toPath(svg) {
  const parts = [];
  for (const m of svg.matchAll(/<(path|circle|ellipse|line|rect|polyline|polygon)\b([^>]*?)\/?>/g)) {
    const t = m[1];
    const a = attrs(m[2]);
    if (t === "path") parts.push(a.d);
    else if (t === "circle") {
      const cx = n(a.cx), cy = n(a.cy), r = n(a.r);
      parts.push(`M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`);
    } else if (t === "ellipse") {
      const cx = n(a.cx), cy = n(a.cy), rx = n(a.rx), ry = n(a.ry);
      parts.push(`M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`);
    } else if (t === "line") parts.push(`M${a.x1} ${a.y1}L${a.x2} ${a.y2}`);
    else if (t === "rect") parts.push(rect(a));
    else {
      const p = a.points.trim().split(/[\s,]+/).map(Number);
      let d = `M${p[0]} ${p[1]}`;
      for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`;
      parts.push(t === "polygon" ? d + "Z" : d);
    }
  }
  return parts.join(" ");
}

let body = "";
for (const [name, candidates] of Object.entries(ICONS)) {
  const file = candidates.map((c) => path.join(dir, c + ".svg")).find((f) => fs.existsSync(f));
  if (!file) throw new Error(`No Lucide icon found for ${name}: ${candidates.join(", ")}`);
  const d = toPath(fs.readFileSync(file, "utf8"));
  if (!d) throw new Error(`Empty path for ${name}`);
  const lit = JSON.stringify(d).replace(/\$/g, "\\$");
  body += `    val ${name}: ImageVector by lazy { lucide("${path.basename(file, ".svg")}", ${lit}) }\n`;
}

const kt = `package com.studyflow.app

// GENERATED by scripts/gen-icons.mjs from Lucide (lucide.dev, ISC licence). Do not edit by hand.

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

private const val STROKE = 1.75f

private fun lucide(name: String, d: String): ImageVector =
    ImageVector.Builder(
        name = name,
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 24f,
        viewportHeight = 24f,
    ).addPath(
        pathData = addPathNodes(d),
        fill = null,
        stroke = SolidColor(Color.Black),
        strokeLineWidth = STROKE,
        strokeLineCap = StrokeCap.Round,
        strokeLineJoin = StrokeJoin.Round,
    ).build()

object Ico {
${body}}
`;
fs.writeFileSync(out, kt);
console.log("wrote", out);
